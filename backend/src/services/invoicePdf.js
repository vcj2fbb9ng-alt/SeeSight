import PDFDocument from 'pdfkit';
import fs from 'node:fs';
import path from 'node:path';

const money = (n, currency) =>
  `${currency} ${Number(n).toFixed(2)}`;

/**
 * Renders an itemized trip invoice to a PDF file.
 *
 * @param {object} params
 * @param {object} params.trip
 * @param {object[]} params.transactions
 * @param {object} params.subtotalsByCategory  { [category]: number }
 * @param {number} params.total
 * @param {string} params.currency
 * @param {string} params.outPath  absolute path to write the PDF to
 */
export function renderInvoicePdf({ trip, transactions, subtotalsByCategory, total, currency, outPath }) {
  fs.mkdirSync(path.dirname(outPath), { recursive: true });

  const doc = new PDFDocument({ size: 'A4', margin: 50 });
  const stream = fs.createWriteStream(outPath);
  doc.pipe(stream);

  // Header
  doc.fontSize(20).fillColor('#1a1a2e').text('SeeSight');
  doc.fontSize(9).fillColor('#6b7280').text('SANDBOX PROTOTYPE — NOT A REAL INVOICE FOR PAYMENT');
  doc.moveDown(0.8);
  doc.fontSize(16).fillColor('#111827').text('Travel Expense Invoice');
  doc.moveDown(1);

  // Trip / traveler summary
  doc.fontSize(10).fillColor('#374151');
  const infoRows = [
    ['Trip', trip.name],
    ['Traveler', trip.traveler_name],
    ['Destination', trip.destination],
    ['Dates', `${trip.start_date} to ${trip.end_date}`],
    ['Trip status', trip.status],
    ['Invoice generated', new Date().toISOString().slice(0, 19).replace('T', ' ') + ' UTC'],
  ];
  infoRows.forEach(([label, value]) => {
    doc.font('Helvetica-Bold').text(`${label}: `, { continued: true }).font('Helvetica').text(String(value));
  });

  doc.moveDown(1);

  // Transactions table
  doc.fontSize(12).fillColor('#111827').font('Helvetica-Bold').text('Transactions');
  doc.moveDown(0.5);

  const colX = { date: 50, merchant: 130, category: 330, amount: 460 };
  const rowTop = () => doc.y;

  function drawTableHeader() {
    const y = rowTop();
    doc.font('Helvetica-Bold').fontSize(9).fillColor('#6b7280');
    doc.text('Date', colX.date, y, { width: 75 });
    doc.text('Merchant', colX.merchant, y, { width: 195 });
    doc.text('Category', colX.category, y, { width: 120 });
    doc.text('Amount', colX.amount, y, { width: 90, align: 'right' });
    doc.moveDown(0.4);
    doc
      .moveTo(50, doc.y)
      .lineTo(545, doc.y)
      .strokeColor('#e5e7eb')
      .stroke();
    doc.moveDown(0.3);
  }

  drawTableHeader();

  doc.font('Helvetica').fontSize(9).fillColor('#111827');
  transactions.forEach((tx) => {
    if (doc.y > 720) {
      doc.addPage();
      drawTableHeader();
      doc.font('Helvetica').fontSize(9).fillColor('#111827');
    }
    const y = doc.y;
    doc.text(tx.occurred_at.slice(0, 10), colX.date, y, { width: 75 });
    doc.text(tx.merchant_name, colX.merchant, y, { width: 195 });
    doc.text(tx.category, colX.category, y, { width: 120 });
    doc.text(money(tx.amount, currency), colX.amount, y, { width: 90, align: 'right' });
    doc.moveDown(0.6);
  });

  doc.moveDown(0.5);
  doc.moveTo(50, doc.y).lineTo(545, doc.y).strokeColor('#e5e7eb').stroke();
  doc.moveDown(0.7);

  // Subtotals by category
  doc.font('Helvetica-Bold').fontSize(11).fillColor('#111827').text('Subtotal by category', 50, doc.y, { width: 495 });
  doc.moveDown(0.3);
  doc.font('Helvetica').fontSize(10);
  Object.entries(subtotalsByCategory).forEach(([category, amount]) => {
    const y = doc.y;
    doc.text(category, colX.merchant, y, { width: 195 });
    doc.text(money(amount, currency), colX.amount, y, { width: 90, align: 'right' });
    doc.moveDown(0.4);
  });

  doc.moveDown(0.5);
  doc.font('Helvetica-Bold').fontSize(13).fillColor('#111827');
  {
    const y = doc.y;
    doc.text('Total', colX.merchant, y, { width: 195 });
    doc.text(money(total, currency), colX.amount, y, { width: 90, align: 'right' });
  }

  doc.moveDown(2);
  doc
    .font('Helvetica')
    .fontSize(8)
    .fillColor('#9ca3af')
    .text(
      'Generated by SeeSight (prototype). Card issuing, transactions, and payment are simulated in sandbox/test mode — no real money moved.',
      { width: 495 }
    );

  doc.end();

  return new Promise((resolve, reject) => {
    stream.on('finish', () => resolve(outPath));
    stream.on('error', reject);
  });
}
